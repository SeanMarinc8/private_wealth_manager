class Database:
    def __init__(self):
        self.conn = psycopg.connect(st.secrets['DATABASE_URL'], sslmode='require', row_factory=dict_row)
    def execute(self, sql, params=()):
        sql = sql.replace('?', '%s').replace('datetime("now")', 'CURRENT_TIMESTAMP')
        return self.conn.execute(sql, params)
    def frame(self, table):
        rows = self.execute(f'SELECT * FROM {table} ORDER BY id').fetchall()
        return pd.DataFrame(rows, columns={'accounts':['id','name','category','balance'], 'holdings':['id','ticker','shares','price','account','avg_cost','updated_at'], 'transactions':['id','description','kind','amount']}[table])
    def commit(self): self.conn.commit()
    def close(self): self.conn.close()

def connect():
    db = Database()
    db.execute('CREATE TABLE IF NOT EXISTS accounts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE, category TEXT NOT NULL, balance DOUBLE PRECISION NOT NULL)')
    db.execute('CREATE TABLE IF NOT EXISTS transactions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, description TEXT NOT NULL, kind TEXT NOT NULL, amount DOUBLE PRECISION NOT NULL)')
    db.execute("CREATE TABLE IF NOT EXISTS holdings (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticker TEXT NOT NULL, shares DOUBLE PRECISION NOT NULL, price DOUBLE PRECISION NOT NULL, account TEXT NOT NULL DEFAULT 'Brokerage', avg_cost DOUBLE PRECISION NOT NULL DEFAULT 0, updated_at TIMESTAMPTZ, UNIQUE(account,ticker))")
    db.commit()
    return db

